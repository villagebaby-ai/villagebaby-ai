"""역방향 내부링크 — 기존 글의 '함께 보면 좋은 …' 목록에 신규 글 <li> 추가.
신규 글의 아웃바운드만으로는 색인·전달력이 부족해서 매 회차 반드시 돌린다.
마크업이 두 종류(신형 <h2>함께 보면 좋은 가이드 / 구형 <div class="related">)라 둘 다 잡는다.
이미 링크가 있으면 건너뛴다(중복 실행 안전).
"""
import os
import re

SITE = "/Users/villagebaby/villagebaby-ai-site"

# 기존 글 슬러그 -> (신규 글 경로, 앵커 텍스트)  · 앵커는 페이지마다 다르게 쓴다
LINKS = {
    "임신-12주-안정기-시작":        ("/guide/임신-13주-증상-해야할-일/", "한 주 뒤 — 임신 13주 (1분기 마지막)"),
    "임신-11주-증상-해야할-일":     ("/guide/임신-13주-증상-해야할-일/", "검사 마감은 13주 6일까지"),
    "2차-기형아-검사-쿼드":         ("/guide/임신-15주-증상-해야할-일/", "언제부터 받나 — 임신 15주"),
    "임신-16주-태동-시작":          ("/guide/임신-15주-증상-해야할-일/", "한 주 전 — 임신 15주"),
    "임산부-치과-치료-급여-지원":    ("/guide/임신-14주-증상-해야할-일/", "치료 받기 좋은 때 — 임신 14주"),
    "임산부-교통비-지원":           ("/guide/임신-14주-증상-해야할-일/", "12주 지나면 신청 — 임신 14주"),
    "임산부-엽산-철분제-무료-지원":   ("/guide/임신-15주-증상-해야할-일/", "철분제는 16주부터 — 임신 15주"),
    "임신-5주-증상-해야할-일":      ("/guide/임신-초기-주차별-가이드/", "4~12주 전체를 한눈에"),
    "임신-10주-증상-해야할-일":     ("/guide/임신-초기-주차별-가이드/", "주차별 마감일 한 장 정리"),
    "임신-주수-계산법":            ("/guide/임신-초기-주차별-가이드/", "내 주차에 뭘 해야 하나"),
    "임신-초기-증상-총정리":        ("/guide/임신-초기-주차별-가이드/", "주차별 할 일 목차"),
    # 2026-08-19 임신 4주 회차
    "임신-확인-검사-소변-혈액":      ("/guide/임신-4주-증상-해야할-일/", "두 줄 뜬 뒤 뭘 하나 — 임신 4주"),
    "임신-초기-출혈-착상혈":         ("/guide/임신-4주-증상-해야할-일/", "가장 이른 주차 — 임신 4주"),
    "임신-초기-술-약-복용":          ("/guide/임신-4주-증상-해야할-일/", "먹던 약 어떻게 하나 — 임신 4주"),
    "임신-준비-영양제":             ("/guide/임신-4주-증상-해야할-일/", "임신 확인 직후 — 임신 4주"),
    "임신-6주-증상-해야할-일":       ("/guide/임신-4주-증상-해야할-일/", "두 주 전 — 임신 4주"),
    "임신-초기-아빠-할-일":          ("/guide/임신-4주-증상-해야할-일/", "가장 처음 — 임신 4주"),
}

PAT = re.compile(r"(함께 보면 좋은 (?:가이드|글)</h[23]>\s*(?:<div[^>]*>\s*)?<ul>)", re.S)

done, skipped = [], []
for slug, (url, anchor) in LINKS.items():
    path = os.path.join(SITE, "guide", slug, "index.html")
    if not os.path.exists(path):
        skipped.append(f"{slug}(파일없음)"); continue
    h = open(path, encoding="utf-8", newline="").read()   # 원본 줄바꿈(CRLF) 보존
    if f'href="{url}"' in h:
        skipped.append(f"{slug}(이미있음)"); continue
    m = PAT.search(h)
    if not m:
        skipped.append(f"{slug}(관련글 섹션 못찾음)"); continue
    nl = "\r\n" if "\r\n" in h else "\n"
    li = f'{nl}<li><a href="{url}">{anchor}</a></li>'
    h = h[:m.end()] + li + h[m.end():]
    open(path, "w", encoding="utf-8", newline="").write(h)
    done.append(slug)

print("추가:", len(done), done)
print("건너뜀:", skipped or "없음")
