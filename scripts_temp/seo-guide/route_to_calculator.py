# 본문 하단 보험 CTA 블록만 정확히 집는다 (`cta app` 은 앱 버튼이라 건드리면 안 됨)
BLOCK = re.compile(
    r'<div class="cta"><p class="ct">(?P<ct>.*?)</p><p class="cd">(?P<cd>.*?)</p>'
    r'<a href="(?P<href>[^"]+)" id="ins-cta"[^>]*>(?P<btn>.*?)</a></div>', re.S)

done, skipped = [], []
for slug, (ct, cd, btn) in COPY.items():
    path = os.path.join(SITE, "guide", slug, "index.html")
    if not os.path.exists(path):
        skipped.append(f"{slug}(파일없음)"); continue
    h = open(path, encoding="utf-8", newline="").read()   # 원본 줄바꿈 보존
    if CALC in h and 'id="ins-cta"' in h and f'href="{CALC}" id="ins-cta"' in h:
        skipped.append(f"{slug}(이미완료)"); continue
    m = BLOCK.search(h)
    if not m:
        skipped.append(f"{slug}(CTA 블록 못찾음)"); continue
    new = (f'<div class="cta"><p class="ct">{ct}</p><p class="cd">{cd}</p>'
           f'<a href="{CALC}" id="ins-cta">{btn}</a></div>')
    h = h[:m.start()] + new + h[m.end():]
    # GA 이벤트 라벨: 목적지가 상담이 아니라 계산기로 바뀌었으니 구분해서 기록
    h = h.replace("track('insurance','cta_main')", "track('calculator','cta_main')")
    open(path, "w", encoding="utf-8", newline="").write(h)
    done.append(slug)

print("변경:", len(done))
for d in done:
    print("  ✓", d)
print("건너뜀:", skipped or "없음")
