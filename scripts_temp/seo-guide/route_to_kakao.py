BLOCK = re.compile(
    r'<div class="cta"><p class="ct">(?P<ct>.*?)</p><p class="cd">(?P<cd>.*?)</p>'
    r'<a href="(?P<href>[^"]+)" id="ins-cta"[^>]*>(?P<btn>.*?)</a></div>', re.S)

done, skipped = [], []
for slug, (ct, cd, btn) in COPY.items():
    path = os.path.join(SITE, "guide", slug, "index.html")
    if not os.path.exists(path):
        skipped.append(f"{slug}(파일없음)"); continue
    h = open(path, encoding="utf-8", newline="").read()
    m = BLOCK.search(h)
    if not m:
        skipped.append(f"{slug}(CTA 블록 못찾음)"); continue
    if m.group("href").startswith(TALK):
        skipped.append(f"{slug}(이미 상담)"); continue
    new = (f'<div class="cta"><p class="ct">{ct}</p><p class="cd">{cd}</p>'
           f'<a href="{utm(slug)}" id="ins-cta" target="_blank" rel="noopener">{btn}</a></div>')
    h = h[:m.start()] + new + h[m.end():]
    h = h.replace("track('calculator','cta_main')", "track('insurance','cta_main')")
    open(path, "w", encoding="utf-8", newline="").write(h)
    done.append(slug)

